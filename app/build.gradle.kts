/** Android versionCode from "major.minor.patch": 1.2.3 -> 10203. Matches core's Version.code(). */
fun versionCodeOf(version: String): Int {
    val parts = version.trim().split(".")
    require(parts.size == 3 && parts.all { p -> p.isNotEmpty() && p.all { it.isDigit() } }) {
        "appVersion '$version' must be major.minor.patch"
    }
    val (major, minor, patch) = parts.map { it.toInt() }
    require(minor < 100 && patch < 100) { "minor and patch must be under 100" }
    return major * 10_000 + minor * 100 + patch
}

